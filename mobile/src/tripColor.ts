/**
 * 여행마다 고정된 색 자리를 고른다.
 *
 * 예전에는 서버가 준 목록의 몇 번째인지로 색을 골랐다. 그래서 여행이 하나 생기거나
 * 목록을 쪽으로 나눠 받으면 같은 여행의 색이 바뀌었고, 기기마다도 달랐다. "그 노란
 * 여행" 이라고 말해도 상대에게는 파란 여행이었다.
 *
 * 여행 id 를 섞어 자리를 고른다. id 는 여행이 만들어질 때 정해져 바뀌지 않으므로
 * 색도 바뀌지 않고, 계산이 기기 안에서 끝나 서버에 칸을 새로 두지 않아도 된다.
 * 서버에 색 칸을 두면 여행마다 줄을 하나 더 읽고 쓰고 마이그레이션까지 해야 하는데,
 * 사람이 색을 고르는 기능이 없는 지금은 그 칸에 담길 값이 결국 이 계산과 같다.
 *
 * 섞는 방법은 FNV-1a(32비트)다. 짧고, 어느 기기에서나 같은 값을 주고, 32비트 정수만
 * 쓰므로 JS 의 큰 수 오차가 끼지 않는다. 비밀을 지키려는 해시가 아니라 색을 고루
 * 흩뜨리려는 것이다. id 가 uuid 라 팔레트 여섯 자리에 고르게 떨어진다.
 *
 * expo 나 react-native 를 가져오지 않는다. `node --test` 로 바로 시험한다.
 */

/** 팔레트(`theme/colors.ts` 의 tripTones)의 자리 수. */
export const TRIP_TONE_COUNT = 6;

export function toneOfTripId(id: string, toneCount: number = TRIP_TONE_COUNT): number {
  // id 가 없는 여행(앱이 처음부터 들고 있는 예시 여행)은 제 tone 을 따로 갖는다.
  if (!id) return 0;
  let 섞은_값 = 0x811c9dc5;
  for (let 자리 = 0; 자리 < id.length; 자리 += 1) {
    섞은_값 ^= id.charCodeAt(자리);
    // 32비트 곱셈. 보통 곱셈은 큰 수에서 값이 뭉개진다.
    섞은_값 = Math.imul(섞은_값, 0x01000193);
  }
  return (섞은_값 >>> 0) % toneCount;
}
