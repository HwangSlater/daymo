// 누르는 것의 크기 토큰.
//
// 버튼, 칩, 입력 칸의 높이와 모서리를 여기 한곳에서 정한다. 이 파일이 생기기
// 전에는 화면마다 눈대중으로 적은 값이 흩어져 있었다. 한 화면 안에서도 38·39·
// 40·42·43·44 가 나란히 놓였는데 그 6px 차이에는 아무 뜻이 없었다. 쓰는 사람
// 눈에는 "왜 살짝씩 다르지" 로만 보이고, 고칠 때도 몇 군데를 고쳐야 하는지
// 알 수가 없었다.
//
// 규칙 근거:
//   docs/product-rules/01-daymo-development-rules.md 5장
//     목록과 카드 높이를 작게 유지한다 · 작은 시각 버튼은 hitSlop 으로 충분한
//     터치 영역을 확보한다
//   docs/product-rules/02-reusable-app-development-rules.md 4장
//     값이 아니라 역할로 정의한다
//
// 쓰는 법은 theme/typography.ts 의 typo 와 같다. 스타일시트에서 숫자를 적지
// 말고 역할 이름을 가져다 쓴다.
//
//   import { 높이, 모서리, 여백, 누름여유 } from "./theme/controls";
//   저장: { height: 높이.저장, borderRadius: 모서리.버튼 },
//
// 여기 없는 크기를 쓰려면 먼저 이 네 단계 중 하나로 들어갈 수 있는지 본다.
// 정말 달라야 하는 자리(배지, 아바타, 아이콘 그림 자체)는 스타일 옆에 왜
// 다른지를 적어 둔다.

/**
 * 누르는 것의 높이. 네 단계뿐이고, 사이의 값은 두지 않는다.
 *
 * 36 과 44 를 둘 다 두는 이유는 한 줄에 여러 개가 나란히 놓이는 칩 때문이다.
 * 필터 칩을 전부 44 로 올리면 목록 위가 한 뼘씩 밀려 본문이 줄어든다. 대신
 * 36 짜리는 손가락으로 누르기에 모자라니 반드시 `누름여유` 로 채운다.
 */
export const 높이 = {
  /** 한 줄에 여러 개가 놓이는 작은 칩. 필터, 태그, 개수 선택. */
  칩: 36,
  /** 보통 버튼과 칩. 손가락 하나가 닿는 가장 작은 크기라 기본값이다. */
  버튼: 44,
  /** 한 줄짜리 입력 칸. 14pt 글자에 위아래 숨을 남긴 높이다. */
  입력: 52,
  /** 시트 맨 아래 저장처럼 화면에서 가장 중요한 것과, 두 줄이 들어가는 큰 줄. */
  저장: 56,
} as const;

/**
 * 모서리.
 *
 * 버튼은 10 이다. 8 은 각져 보이고 12 는 알약에 가까워, 종이 수첩 느낌을
 * 해치지 않으면서 눌리는 것처럼 보이는 자리가 그 사이다.
 */
export const 모서리 = {
  /** 버튼, 칩, 입력 칸. */
  버튼: 10,
  /** 카드와 구역처럼 안에 다른 것을 담는 것. 버튼보다 커야 층이 보인다. */
  구역: 16,
  /** 동그랗게 만들 것. 알약 모양 칩과 원형 아이콘 단추. */
  원: 999,
} as const;

/** 누르는 것 안쪽 여백. 세로는 줄 사이, 가로는 글자와 테두리 사이다. */
export const 여백 = {
  /** 칩처럼 한 줄만 들어가는 것의 위아래. */
  세로좁게: 8,
  /** 두 줄이 들어가거나 테두리가 있는 것의 위아래. */
  세로: 12,
  /** 칩과 작은 버튼의 좌우. */
  가로좁게: 12,
  /** 시트와 가로로 긴 버튼의 좌우. */
  가로: 16,
} as const;

/**
 * 44 보다 작게 그린 것에 줄 `hitSlop` 값.
 *
 * 작게 그리되 누르기는 편해야 한다. 그린 높이와 `높이.버튼` 사이의 모자란
 * 만큼을 반으로 나눠 사방으로 넓힌다. 36 이면 4, 34 면 5 가 나온다.
 * 이미 44 이상이면 0 이므로 그대로 넘겨도 된다.
 */
export function 누름여유(그린높이: number): number {
  if (그린높이 >= 높이.버튼) return 0;
  return Math.ceil((높이.버튼 - 그린높이) / 2);
}
